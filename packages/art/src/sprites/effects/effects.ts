/** Soft blob shadows: a darker core with a lighter rim, drawn under everything. */
function blob(name: string, size: [number, number], grid: string) {
  return sprite({
    name,
    group: "effects",
    size,
    origin: [Math.floor(size[0] / 2), Math.floor(size[1] / 2)],
    outline: false,
    palette: { ".": null, z: "ink.dark", i: "ink.mid" },
    frames: { blob: grid },
    anim: { still: { frames: ["blob"], fps: 1 } },
  });
}

