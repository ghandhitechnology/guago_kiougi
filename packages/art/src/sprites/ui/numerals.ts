import { outlined } from "../../draw.ts";
import { type GlyphFontDef, glyphs } from "../../format.ts";

/**
 * Damage numerals (PLAN §6 "Hit feel"): chunky two-tone digits with a dark outline and a
 * drop shadow, so a number reads over any field. Korean units 만, 억, 조 follow the digits.
 * Small for ordinary hits, large for heavy hits; each has a 치명타 colouring.
 */
const palette = {
  ".": null,
  o: "ink.deep",
  c: "ink.deep",
  W: "stone.bright",
  p: "stone.pale",
} as const;

/** Crit: gold numbers outlined in deep wine. */
const crit = { "stone.bright": "gold.pale", "stone.pale": "gold.light", "ink.deep": "red.deep" };

function font(name: string, split: number, masks: Record<string, string>): GlyphFontDef {
  const grids = Object.fromEntries(Object.entries(masks).map(([k, m]) => [k, outlined(m, split)]));
  const height = (Object.values(grids)[0] ?? "").trim().split("\n").length;
  return glyphs({
    name,
    palette,
    lone: "c",
    height,
    base: height - 2,
    spacing: -1,
    glyphs: grids,
  });
}

