/**
 * What the world says when nobody is talking: every notice, lore object and seat on the maps
 * (`packages/content/src/maps/*.ts`), read by the map interactable's id. A notice has a real
 * notice on it, a shelf a real trophy, a seat a reason to sit. Flat fact and a deadpan last
 * clause, in the narrator's written 해라체; a notice is in the notice's own clipped style.
 *
 * The server reads a description by id alone (`describe` in apps/server/src/world-maps.ts), so
 * an id used on two maps shares one: `menu`, `ranking`, `gnomon` and `altar` are written to fit
 * every place they stand.
 */
import { Writer } from "./author.ts";
import type { CopyPart, Description } from "./schema.ts";

const w = new Writer("thing");

type Entry = readonly [id: string, name: string, desc: string];

const things = (scope: string, entries: readonly Entry[]): Description[] => {
  const s = w.scope(scope);
  return entries.map(([id, name, desc]) => ({
    id,
    kind: "prop",
    name: s.t(name),
    desc: s.t(desc),
  }));
};

